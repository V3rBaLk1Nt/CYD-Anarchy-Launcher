size_t anarchyToolCount() { return sizeof(tools) / sizeof(tools[0]); }

const AnarchyTool *anarchyToolAt(size_t index) {
    return index < anarchyToolCount() ? &tools[index] : nullptr;
}

const char *anarchyToolStatusName(AnarchyToolStatus status) {
    switch (status) {
        case Status::Working: return "WORKING";
        case Status::Partial: return "PARTIAL";
        case Status::HardwareDependent: return "HARDWARE-DEPENDENT";
        case Status::Research: return "RESEARCH";
        case Status::NotImplemented: return "NOT IMPLEMENTED";
    }
    return "NOT IMPLEMENTED";
}

const char *anarchyToolGroupName(AnarchyToolGroup group) {
    switch (group) {
        case Group::Network: return "Network / red-blue labs";
        case Group::Hardware: return "Hardware / sensors";
        case Group::Files: return "Files / tool loading";
        case Group::Codes: return "Language / codes";
        case Group::System: return "System / War Room";
        case Group::Research: return "Research / concepts";
    }
    return "Unknown";
}
